@Composable
fun SectionHeader(text: String, modifier: Modifier = Modifier, action: (@Composable () -> Unit)? = null) {
    Row(modifier.fillMaxWidth().padding(top = 16.dp, bottom = 8.dp), verticalAlignment = Alignment.CenterVertically) {
        Text(text, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.SemiBold,
            modifier = Modifier.weight(1f).semantics { heading() })
        action?.invoke()
    }
}

/** Mandatory label on any AI-generated content. Shows review state, syllabus outcomes and sources. */
@Composable
fun AiProvenanceCard(provenance: AiProvenance?, status: ReviewStatus, modifier: Modifier = Modifier) {
    if (provenance == null) return
    var expanded by remember { mutableStateOf(false) }
    val (label, container) = when (status) {
        ReviewStatus.DRAFT_AI -> "AI draft · not yet reviewed" to MaterialTheme.colorScheme.tertiaryContainer
        ReviewStatus.TEACHER_EDITED -> "AI-assisted · edited, awaiting approval" to MaterialTheme.colorScheme.tertiaryContainer
        ReviewStatus.APPROVED -> "AI-assisted · approved by teacher" to MaterialTheme.colorScheme.primaryContainer
        ReviewStatus.REJECTED -> "AI draft · rejected" to MaterialTheme.colorScheme.errorContainer
    }
    Card(colors = CardDefaults.cardColors(containerColor = container), modifier = modifier.fillMaxWidth(),
        onClick = { expanded = !expanded }) {
        Column(Modifier.padding(12.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(Icons.Outlined.AutoAwesome, contentDescription = null)
                Spacer(Modifier.width(8.dp))
                Text(label, style = MaterialTheme.typography.labelLarge, modifier = Modifier.weight(1f))
                Icon(Icons.Outlined.Info, contentDescription = if (expanded) "Hide details" else "Show details")
            }
            if (provenance.isOfflineTemplate) {
                Text("Offline template: structure only. Fill in specifics before use.", style = MaterialTheme.typography.bodySmall,
                    modifier = Modifier.padding(top = 4.dp))
            }
            if (expanded) {
                Spacer(Modifier.height(8.dp))
                Text("Syllabus outcomes: " + provenance.syllabusOutcomesCited.joinToString().ifEmpty { "none cited" },
                    style = MaterialTheme.typography.bodySmall)
                Text(
                    if (provenance.citations.isEmpty()) "Sources: ${provenance.citationNote}"
                    else "Sources: " + provenance.citations.joinToString { "${it.title} (${it.source}, ${it.licence})" },
                    style = MaterialTheme.typography.bodySmall,
                )
                Text("Generated by ${provenance.generatedBy}", style = MaterialTheme.typography.bodySmall)
            }
        }
    }
}

@Composable
fun StatusPill(text: String, modifier: Modifier = Modifier, color: androidx.compose.ui.graphics.Color = MaterialTheme.colorScheme.secondaryContainer) {
    Surface(color = color, shape = MaterialTheme.shapes.small, modifier = modifier) {
        Text(text, style = MaterialTheme.typography.labelSmall, modifier = Modifier.padding(horizontal = 8.dp, vertical = 3.dp))
    }
}

@Composable
fun <T> ChipSelector(
    options: List<T>, selected: Set<T>, label: (T) -> String, onToggle: (T) -> Unit, modifier: Modifier = Modifier,
) {
    FlowRow(modifier, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        options.forEach { o ->
            FilterChip(selected = o in selected, onClick = { onToggle(o) }, label = { Text(label(o)) })
        }
    }
}

/** Editable bullet list used by lesson plan sections. */
@Composable
fun EditableList(items: List<String>, onChange: (List<String>) -> Unit, itemLabel: String, modifier: Modifier = Modifier) {
    Column(modifier) {
        items.forEachIndexed { i, item ->
            Row(verticalAlignment = Alignment.CenterVertically) {
                OutlinedTextField(
                    value = item, onValueChange = { v -> onChange(items.toMutableList().also { it[i] = v }) },
                    modifier = Modifier.weight(1f).padding(vertical = 2.dp), textStyle = MaterialTheme.typography.bodyMedium,
                    label = { Text("$itemLabel ${i + 1}") },
                )
                IconButton(onClick = { onChange(items.filterIndexed { j, _ -> j != i }) },
                    modifier = Modifier.semantics { contentDescription = "Remove $itemLabel ${i + 1}" }) {
                    Icon(Icons.Outlined.Close, contentDescription = null)
                }
            }
        }
        TextButton(onClick = { onChange(items + "") }) { Text("+ Add ${itemLabel.lowercase()}") }
    }
}

@Composable
fun EmptyState(title: String, body: String, modifier: Modifier = Modifier, action: (@Composable () -> Unit)? = null) {
    Column(modifier.fillMaxWidth().padding(32.dp), horizontalAlignment = Alignment.CenterHorizontally) {
        Text(title, style = MaterialTheme.typography.titleMedium)
        Text(body, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.padding(top = 4.dp, bottom = 12.dp))
        action?.invoke()
    }
}

/** Constrains content width on tablets so forms stay readable. */
@Composable
fun ContentWidth(modifier: Modifier = Modifier, content: @Composable ColumnScope.() -> Unit) {
    Box(modifier.fillMaxWidth(), contentAlignment = Alignment.TopCenter) {
        Column(Modifier.widthIn(max = 840.dp).fillMaxWidth(), content = content)
    }
}
